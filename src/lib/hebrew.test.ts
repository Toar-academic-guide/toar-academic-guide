import { describe, expect, it } from 'vitest';
import { withBet } from './hebrew';

describe('withBet', () => {
  it.each([
    ['האוניברסיטה העברית בירושלים', 'באוניברסיטה העברית בירושלים'],
    ['המכללה האקדמית אונו', 'במכללה האקדמית אונו'],
    ['המכון הטכנולוגי חולון', 'במכון הטכנולוגי חולון'],
    ['אוניברסיטת חיפה', 'באוניברסיטת חיפה'],
    ['המטוס ומערכותיו', 'במטוס ומערכותיו'],
    ['המסוק ומערכותיו', 'במסוק ומערכותיו'],
    ['היסטוריה', 'בהיסטוריה'],
    ['הסטוריה ותע"י', 'בהסטוריה ותע"י'],
    ['הבעה עברית', 'בהבעה עברית'],
    ['הנדסה וטכנולוגיה', 'בהנדסה וטכנולוגיה'],
    ['הנדסת אוטוטק', 'בהנדסת אוטוטק'],
    ['הנדסאים תל-אביב', 'בהנדסאים תל-אביב'],
    ['הגנת סייבר', 'בהגנת סייבר'],
    ['הדפסת אופסט', 'בהדפסת אופסט'],
    ['הפקות בתקשורת', 'בהפקות בתקשורת'],
    ['השפעה ויוזמה חברתית', 'בהשפעה ויוזמה חברתית'],
    ['הולנדית', 'בהולנדית'],
    ['הונגרית', 'בהונגרית'],
  ])('prefixes %s as %s', (name, expected) => {
    expect(withBet(name)).toBe(expected);
  });
});
